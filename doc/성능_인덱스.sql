-- Supabase 대시보드 > SQL Editor 에 붙여 넣고 실행하세요. 여러 번 실행해도 안전합니다 (if not exists).
-- 2026-11-12 기준 데이터로 중복을 확인했습니다: 현장정보.현장번호, 권한.영업사원ID, 정산정보(영업사원, 정산월) 모두 중복 없음.

-- 0) (참고) 지금 있는 인덱스 확인 — 실행 전에 한 번 보고 싶으면 이 줄만 따로 실행
-- select tablename, indexname, indexdef from pg_indexes where schemaname = 'public' order by tablename, indexname;

-- 1) 현장정보 ------------------------------------------------------------------
--  · 현장번호: 입금·정산·A/S·상담이 모두 현장번호로 찾는다. 중복 금지 제약을 겸한다
--    (doc/현장정보_현장번호_유니크.sql을 이미 실행했다면 같은 이름이라 건너뛴다)
create unique index if not exists "현장정보_현장번호_key" on public."현장정보" ("현장번호");
--  · 영업사원: RD 로그인 시 '본인 현장만', 열외 계정 제외 조건
create index if not exists "현장정보_영업사원_idx" on public."현장정보" ("영업사원");

-- 2) 입금내역 ------------------------------------------------------------------
--  · 현장 상세의 입금내역, 자동 계산(한샘 외 시공비·거래처환불), 현장 변경 반영
create index if not exists "입금내역_현장번호_입금구분_idx" on public."입금내역" ("현장번호", "입금구분");
--  · RD 로그인 시 '본인 입금내역만'
create index if not exists "입금내역_영업사원_idx" on public."입금내역" ("영업사원");

-- 3) 승인필요입금내역 ----------------------------------------------------------
--  · 승인 필요 목록·상단 알림 건수: 승인여부 = '승인대기' 를 요청 순으로
create index if not exists "승인필요입금내역_승인여부_요청일시_idx" on public."승인필요입금내역" ("승인여부", "요청일시", id);
--  · 내 요청 화면·알림 건수: 요청자 + 승인여부
create index if not exists "승인필요입금내역_요청자_승인여부_idx" on public."승인필요입금내역" ("요청자", "승인여부");
--  · 수정·삭제 요청의 대상 입금내역
create index if not exists "승인필요입금내역_입금내역id_idx" on public."승인필요입금내역" ("입금내역id") where "입금내역id" is not null;
--  · 현장 변경 반영(현장번호·고객명·영업사원 일괄 수정)
create index if not exists "승인필요입금내역_현장번호_idx" on public."승인필요입금내역" ("현장번호");

-- 4) 한샘 업로드 데이터 --------------------------------------------------------
--  · 현장 자동 계산·정산: 계약현장번호 + 주문상태 '확정' (주문번호는 중복이 있어 고유 제약은 걸지 않음)
create index if not exists "한샘주문진도정보_계약현장번호_주문상태_idx" on public."한샘주문진도정보" ("계약현장번호", "주문상태", "주문번호");
--  · 정산의 추가시공비
create index if not exists "한샘추가시공비_현장코드_idx" on public."한샘추가시공비" ("현장코드");

-- 5) 정산정보 ------------------------------------------------------------------
--  · 영업사원·정산월로 찾고 같은 달은 갱신한다 → 고유 제약으로 중복 저장도 막는다
create unique index if not exists "정산정보_영업사원_정산월_key" on public."정산정보" ("영업사원", "정산월");

-- 6) 권한 ----------------------------------------------------------------------
--  · 로그인·영업사원 조회. 영업사원ID 중복 금지를 겸한다
create unique index if not exists "권한_영업사원ID_key" on public."권한" ("영업사원ID");

-- 7) A/S ----------------------------------------------------------------------
--  · 원 접수 삭제 시 연결 해제(on delete set null)가 전체를 훑지 않게
create index if not exists "AS접수_원접수id_idx" on public."AS접수" ("원접수id") where "원접수id" is not null;

-- 통계 갱신 (새 인덱스를 바로 쓰도록)
analyze public."현장정보", public."입금내역", public."승인필요입금내역", public."한샘주문진도정보",
        public."한샘추가시공비", public."정산정보", public."권한", public."AS접수";
