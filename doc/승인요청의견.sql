-- 입금 승인 요청에 대해 관리자와 요청자가 주고받는 확인사항·의견
-- 승인 요청(승인필요입금내역)이 지워지면 의견도 함께 지워진다
create table if not exists public."승인요청의견" (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "요청id" bigint not null references public."승인필요입금내역"(id) on delete cascade,
  "작성자" bigint,
  "작성자이름" text,
  "구분" text not null check ("구분" in ('관리자', '요청자')),
  "내용" text not null
);

create index if not exists "승인요청의견_요청id_idx" on public."승인요청의견" ("요청id");
