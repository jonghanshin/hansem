-- 입금 등록 화면 '현금영수증' → '영수증' 선택값 변경에 맞춰 기존 데이터의 값을 새 이름으로 바꾼다.
--   발행완료 → 현금영수증발행완료
--   발급필요 → 현금영수증발행필요
--   (예전 표기 발행 / 미발행 / 미발급 도 함께 정리)
-- 새 선택값: 현금영수증발행완료, 현금영수증발행필요, 세금계산서발행완료, 세금계산서발행필요, 발급불필요, 카드결제
-- 컬럼 이름("현금영수증")은 바꾸지 않는다.
-- Supabase 대시보드 > SQL Editor 에 붙여 넣고 한 번 실행하세요. (여러 번 실행해도 결과는 같습니다)

begin;

update public."입금내역" set "현금영수증" = case trim("현금영수증")
    when '발행완료' then '현금영수증발행완료'
    when '발행'     then '현금영수증발행완료'
    when '발급필요' then '현금영수증발행필요'
    when '미발행'   then '현금영수증발행필요'
    when '미발급'   then '현금영수증발행필요'
  end
where trim("현금영수증") in ('발행완료', '발행', '발급필요', '미발행', '미발급');

update public."승인필요입금내역" set "현금영수증" = case trim("현금영수증")
    when '발행완료' then '현금영수증발행완료'
    when '발행'     then '현금영수증발행완료'
    when '발급필요' then '현금영수증발행필요'
    when '미발행'   then '현금영수증발행필요'
    when '미발급'   then '현금영수증발행필요'
  end
where trim("현금영수증") in ('발행완료', '발행', '발급필요', '미발행', '미발급');

commit;

-- 확인: 값별 건수
select "현금영수증", count(*) from public."입금내역" group by 1 order by 2 desc;
